'use strict';
const {spawn} = require('node:child_process');
const {once} = require('node:events');
const assert = require('node:assert/strict');
const path = require('node:path');
const server = spawn(process.execPath,[path.join(__dirname,'mock-server.js'),'--port','18084','--ephemeral'],
  {stdio:['ignore','pipe','pipe'],windowsHide:true});
let count=0;
function check(v,message) {assert.ok(v,message);count++;}
async function req(url,method='GET',data,token) {
  const r=await fetch('http://localhost:18084/api'+url,{method,
    headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},
    body:data===undefined?undefined:JSON.stringify(data)});
  const text=await r.text();return {status:r.status,data:text?JSON.parse(text):null};
}
async function main() {
  await Promise.race([once(server.stdout,'data'),once(server,'exit').then(()=>{throw Error('Server failed');})]);
  const login=async name=>(await req('/auth/login','POST',{username:name,password:name+'123'})).data;
  const client=await login('client'),manager=await login('manager'),admin=await login('admin'),photographer=await login('photographer');
  const day=new Date(Date.now()+45*86400000).toISOString().slice(0,10);
  const input={hallId:1,photographerIds:[1],date:day,durationHours:2,participants:2,shootingType:'Портретная',email:'client@example.com'};
  check((await req('/bookings','POST',input)).status===401,'guest cannot book');
  check((await req('/bookings','POST',input,photographer.accessToken)).status===403,'photographer cannot book as client');
  check((await req('/bookings','POST',{...input,clientId:2},client.accessToken)).status===403,'client cannot book for someone else');
  const created=await req('/bookings','POST',{...input,status:'completed',accessCode:'FORGED-ADMIN',clientName:'Someone else'},client.accessToken);
  check(created.status===201,'client booking succeeds: '+JSON.stringify(created.data));
  check(created.data.client.id===client.user.clientId,'owner taken from authenticated user');
  check(created.data.status==='active','client cannot forge status');
  check(created.data.accessCode!=='FORGED-ADMIN' && /^BR-/.test(created.data.accessCode),'code generated by server');
  const mine=await req('/account/bookings','GET',undefined,client.accessToken);
  check(mine.data.some(b=>b.id===created.data.id),'created booking appears in own account');
  const collision=await req('/bookings','POST',input,client.accessToken);
  check(collision.status===409,'occupied hall produces HTTP 409');
  check((await req('/bookings','POST',{...input,date:'2020-01-01'},client.accessToken)).status===422,'past dates forbidden');
  check((await req('/bookings','POST',{...input,hallId:99999},client.accessToken)).status===422,'missing hall rejected');
  check((await req('/bookings/'+created.data.id,'PUT',input,client.accessToken)).status===403,'client cannot use staff editing');
  check((await req('/bookings/'+created.data.id,'DELETE',undefined,client.accessToken)).status===403,'client cannot delete through staff API');
  for (const collection of ['halls','photographers','equipment']) {
    check((await req('/'+collection,'GET',undefined,manager.accessToken)).status===200,'manager can read '+collection);
    for (const [resource,method,data] of [
      ['/'+collection,'POST',{}],['/'+collection+'/1','PUT',{}],['/'+collection+'/1','DELETE',undefined],
      ['/'+collection+'/bulk-delete','POST',{ids:[1]}],['/'+collection+'/1/restore','POST',{}],
      ['/'+collection+'/1?hard=true','DELETE',undefined],['/'+collection+'/bulk-delete?hard=true','POST',{ids:[1]}],
    ]) check((await req(resource,method,data,manager.accessToken)).status===403,'manager denied '+method+' '+resource);
  }
  const person=await req('/clients','POST',{fullName:'Клиент менеджера',email:'manager-client@example.com',clientType:'Частный'},manager.accessToken);
  check(person.status===201,'manager creates clients');
  const staffBooking=await req('/bookings','POST',{...input,date:new Date(Date.now()+46*86400000).toISOString().slice(0,10),clientId:person.data.id,accessCode:'MANAGER-BOOK'},manager.accessToken);
  check(staffBooking.status===201 && staffBooking.data.client.id===person.data.id,'manager books for a client');
  check((await req('/bookings/'+staffBooking.data.id+'/complete','POST',{},manager.accessToken)).status===200,'manager completes bookings');
  check((await req('/bookings/'+staffBooking.data.id+'/restore','POST',{},manager.accessToken)).status===403,'manager cannot restore bookings');
  check((await req('/bookings/'+staffBooking.data.id+'?hard=true','DELETE',undefined,manager.accessToken)).status===403,'manager cannot purge bookings');
  check((await req('/users','GET',undefined,manager.accessToken)).status===403,'manager cannot read user administration');
  check((await req('/users/4/role','PATCH',{role:'admin'},manager.accessToken)).status===403,'manager cannot assign roles');
  check((await req('/admin/statistics','GET',undefined,manager.accessToken)).status===403,'manager cannot view admin stats');
  const hall=await req('/halls','POST',{name:'Новый зал администратора',code:'ADMIN-TEST',style:'Лофт',capacity:5,hourlyRate:2000},admin.accessToken);
  check(hall.status===201,'admin manages studio catalogue');
  check((await req('/halls/'+hall.data.id,'DELETE',undefined,admin.accessToken)).status===204,'admin soft delete');
  check((await req('/halls/'+hall.data.id+'/restore','POST',{},admin.accessToken)).status===200,'admin restore');
  check((await req('/halls/'+hall.data.id+'?hard=true','DELETE',undefined,admin.accessToken)).status===204,'admin hard delete');
  console.log(`Booking and roles: ${count} checks passed`);
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>server.kill());
